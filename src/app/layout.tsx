import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "../styles/globals.css";
import Providers from "<prefix>/components/providers/providers";
import { Toaster, toast } from "sonner";
import Navbar from "<prefix>/components/layout/Navbar";
import Footer from "<prefix>/components/layout/Footer";
import { verifyToken } from "../features/auth/server/auth.actions";
import { getCartItems } from "<prefix>/features/cart/server/cart.actions";
import { CartValuesType } from "<prefix>/features/cart/slices/cart.slice";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const authStates = await verifyToken();
  let cartValues: CartValuesType = {
    status: "",
    message: "",
    numOfCartItems: 0,
    cartId: null,
    data: {
      products: [],
      totalCartPrice: 0,
    },
  };
  if (authStates.isAuthenticated === true) {
    const cartResponse = await getCartItems();
    if (cartResponse.status === "success") {
      cartValues = cartResponse;
    }
  }

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Providers
          preloadedState={{
            authReducer: authStates,
            cartReducer: cartValues,
          }}
        >
          <Navbar />
          {children}
          <Footer />
          <Toaster richColors position="top-right" />
        </Providers>
      </body>
    </html>
  );
}
